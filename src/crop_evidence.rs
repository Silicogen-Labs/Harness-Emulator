//! Bounded cell-aligned crops of the existing terminal screenshot renderer.
use crate::locators::{CellRect, ObservationIdentity};
use crate::protocol::FrameSnapshot;
use anyhow::{Context, Result, bail};
use resvg::{
    tiny_skia::{Pixmap, Transform},
    usvg::{Options, Tree},
};
use rmcp::schemars;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

pub const MAX_CROP_PIXELS: u64 = 8_000_000;
pub const MAX_CROP_PNG_BYTES: usize = 4 * 1024 * 1024;
const FONT: &[u8] = include_bytes!("../web/fonts/DejaVuSansMono.ttf");
const CELL_WIDTH: u32 = 10;
const CELL_HEIGHT: u32 = 20;
const TERMINAL_LEFT: u32 = 16;
const TERMINAL_TOP: u32 = 34;

#[derive(Debug, Clone, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct CropRequest {
    pub region: CellRect,
    pub scale: u8,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct CropMetadata {
    pub source: ObservationIdentity,
    pub region: CellRect,
    pub scale: u8,
    pub width_px: u32,
    pub height_px: u32,
    pub render_profile: String,
    pub font_sha256: String,
    pub wide_glyph_clipped: bool,
    pub png_sha256: String,
}

/// Raw operational image bytes. Integration must redact the source as required
/// before rendering public evidence, reserve quota, and assign an artifact ID.
#[derive(Debug)]
pub struct CroppedEvidence {
    pub png: Vec<u8>,
    pub metadata: CropMetadata,
}

pub fn render_crop(
    frame: &FrameSnapshot,
    source: &ObservationIdentity,
    request: &CropRequest,
) -> Result<CroppedEvidence> {
    validate_source(frame, source)?;
    crate::locators::validate_region(frame, request.region)?;
    if !(1..=4).contains(&request.scale) {
        bail!("crop scale must be an integer in 1..=4")
    }
    // The upstream renderer expects resolved colors and cell widths; reject
    // malformed attributes instead of allowing SVG injection or unbounded SVG.
    validate_render_input(frame)?;
    let width = u32::from(request.region.col_end - request.region.col_start)
        * CELL_WIDTH
        * u32::from(request.scale);
    let height = u32::from(request.region.row_end - request.region.row_start)
        * CELL_HEIGHT
        * u32::from(request.scale);
    if u64::from(width) * u64::from(height) > MAX_CROP_PIXELS {
        bail!("crop pixel budget exceeded")
    }
    let full_svg = crate::screenshot::frame_svg(frame);
    // Extract only the terminal section generated by the shared renderer.
    // Decorations and session labels are excluded from the cropped SVG tree.
    let marker = format!(
        "<rect x=\"{TERMINAL_LEFT}\" y=\"{TERMINAL_TOP}\" width=\"{}\" height=\"{}\" fill=\"{}\"/>",
        u32::from(frame.cols) * CELL_WIDTH,
        u32::from(frame.rows) * CELL_HEIGHT,
        frame.default_background
    );
    let start = full_svg
        .find(&marker)
        .context("unsupported screenshot renderer layout: terminal background not found")?;
    let body = full_svg[start..]
        .strip_suffix("</svg>")
        .context("unsupported screenshot renderer SVG suffix")?;
    let left = TERMINAL_LEFT + u32::from(request.region.col_start) * CELL_WIDTH;
    let top = TERMINAL_TOP + u32::from(request.region.row_start) * CELL_HEIGHT;
    let svg = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{width}\" height=\"{height}\" viewBox=\"{left} {top} {} {}\">{body}</svg>",
        width / u32::from(request.scale),
        height / u32::from(request.scale)
    );
    let mut options = Options::default();
    options.fontdb_mut().load_font_data(FONT.to_vec());
    let tree = Tree::from_str(&svg, &options).context("parse shared terminal crop SVG")?;
    let mut pixmap = Pixmap::new(width, height).context("allocate bounded crop")?;
    resvg::render(&tree, Transform::identity(), &mut pixmap.as_mut());
    let png = pixmap.encode_png()?;
    if png.len() > MAX_CROP_PNG_BYTES {
        bail!("crop PNG byte budget exceeded")
    }
    Ok(CroppedEvidence {
        metadata: CropMetadata {
            source: source.clone(),
            region: request.region,
            scale: request.scale,
            width_px: width,
            height_px: height,
            render_profile: "frame_svg-terminal-10x20-origin16x34-resvg0.48.1-bundled-font-v1"
                .into(),
            font_sha256: format!("{:x}", Sha256::digest(FONT)),
            wide_glyph_clipped: wide_clipped(frame, request.region),
            png_sha256: format!("{:x}", Sha256::digest(&png)),
        },
        png,
    })
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct PixelTolerance {
    pub max_channel_delta: u8,
    pub max_different_pixels: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
pub struct PixelComparison {
    pub matched: bool,
    pub different_pixels: u64,
    pub max_channel_delta_seen: u8,
}

/// Optional visual comparison. It never substitutes for deterministic cell and
/// style diffs. Incompatible render/font/geometry/region inputs fail explicitly.
pub fn compare_crop_pixels(
    left: &CroppedEvidence,
    right: &CroppedEvidence,
    tolerance: PixelTolerance,
) -> Result<PixelComparison> {
    let a = &left.metadata;
    let b = &right.metadata;
    if a.width_px != b.width_px
        || a.height_px != b.height_px
        || a.scale != b.scale
        || a.region != b.region
        || a.render_profile != b.render_profile
        || a.font_sha256 != b.font_sha256
        || a.source.cols != b.source.cols
        || a.source.rows != b.source.rows
        || a.wide_glyph_clipped != b.wide_glyph_clipped
    {
        bail!("pixel_comparison_incompatible: geometry, region, renderer or font settings differ")
    }
    let pixels = u64::from(a.width_px) * u64::from(a.height_px);
    if tolerance.max_different_pixels > pixels {
        bail!("invalid pixel tolerance")
    }
    let left = decode_bounded(left)?;
    let right = decode_bounded(right)?;
    let mut different_pixels = 0;
    let mut max_delta = 0;
    for (a, b) in left
        .data()
        .chunks_exact(4)
        .zip(right.data().chunks_exact(4))
    {
        let delta = a
            .iter()
            .zip(b)
            .map(|(a, b)| a.abs_diff(*b))
            .max()
            .unwrap_or(0);
        max_delta = max_delta.max(delta);
        different_pixels += u64::from(delta > tolerance.max_channel_delta);
    }
    Ok(PixelComparison {
        matched: different_pixels <= tolerance.max_different_pixels,
        different_pixels,
        max_channel_delta_seen: max_delta,
    })
}

fn decode_bounded(crop: &CroppedEvidence) -> Result<Pixmap> {
    if crop.png.len() > MAX_CROP_PNG_BYTES
        || crop.png.len() < 24
        || &crop.png[..8] != b"\x89PNG\r\n\x1a\n"
    {
        bail!("invalid bounded crop PNG")
    }
    let width = u32::from_be_bytes(crop.png[16..20].try_into()?);
    let height = u32::from_be_bytes(crop.png[20..24].try_into()?);
    if width == 0
        || height == 0
        || width != crop.metadata.width_px
        || height != crop.metadata.height_px
        || u64::from(width) * u64::from(height) > MAX_CROP_PIXELS
        || format!("{:x}", Sha256::digest(&crop.png)) != crop.metadata.png_sha256
    {
        bail!("crop PNG dimensions/hash mismatch")
    }
    Pixmap::decode_png(&crop.png).context("decode crop PNG")
}

fn validate_source(frame: &FrameSnapshot, source: &ObservationIdentity) -> Result<()> {
    crate::locators::validate_frame(frame)?;
    if [&source.session_id, &source.run_id, &source.frame_id]
        .iter()
        .any(|value| value.is_empty() || value.len() > 128)
    {
        bail!("invalid crop source identity length")
    }
    if source.session_id != frame.session_id
        || source.run_id != frame.run_id
        || source.frame_id != frame.frame_id
        || source.cols != frame.cols
        || source.rows != frame.rows
    {
        bail!("crop_source_incompatible")
    }
    Ok(())
}

fn validate_render_input(frame: &FrameSnapshot) -> Result<()> {
    fn color(value: &str) -> bool {
        value.len() == 7
            && value.starts_with('#')
            && value.as_bytes()[1..].iter().all(u8::is_ascii_hexdigit)
    }
    if !color(&frame.default_background) || !color(&frame.cursor.color) {
        bail!("unsupported resolved screenshot color")
    }
    let mut text_bytes = 0usize;
    for row in &frame.cells {
        for cell in row {
            text_bytes = text_bytes.saturating_add(cell.text.len());
            if cell.width > 2
                || !color(&cell.resolved_background)
                || !color(&cell.resolved_foreground)
                || !["none", "single", "double", "curly", "dotted", "dashed"]
                    .contains(&cell.underline.as_str())
            {
                bail!("unsupported resolved cell width/color/underline")
            }
        }
    }
    if text_bytes > 512 * 1024 {
        bail!("crop render text budget exceeded")
    }
    Ok(())
}

fn wide_clipped(frame: &FrameSnapshot, region: CellRect) -> bool {
    (region.row_start..region.row_end).any(|row| {
        frame.cells[usize::from(row)]
            .iter()
            .enumerate()
            .any(|(col, cell)| {
                let end = col + cell.width;
                cell.width > 1
                    && col < usize::from(region.col_end)
                    && end > usize::from(region.col_start)
                    && (col < usize::from(region.col_start) || end > usize::from(region.col_end))
            })
    })
}
